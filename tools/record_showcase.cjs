/* Optional recording utility: npm install playwright, then serve repo on 8768. */
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const fs=require('fs');
const path=require('path');
(async()=>{
 const output=path.resolve(process.env.DEMO_OUTPUT||'docs/media');fs.mkdirSync(output,{recursive:true});
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--no-proxy-server']});
 const context=await browser.newContext({viewport:{width:1440,height:1000},recordVideo:{dir:path.resolve('demo/recordings'),size:{width:1440,height:1000}}});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.DEMO_URL||'http://127.0.0.1:8768/demo/');await page.waitForFunction(()=>document.getElementById('estimate').textContent.includes('12,000'));
 await page.addStyleTag({content:'#demo-caption{position:fixed;bottom:22px;left:220px;right:24px;z-index:99;background:#142033;color:#fff;padding:18px 26px;border:1px solid #ffffff33;border-radius:8px;font:600 30px/1.55 "Microsoft YaHei",sans-serif;box-shadow:0 4px 24px #0005;pointer-events:none;text-wrap:pretty} .panel{font-size:16px} .hint,.muted,.choice small{font-size:14px} .chart-caption{font-size:14px}'});
 await page.evaluate(()=>{const d=document.createElement('div');d.id='demo-caption';document.body.append(d);});
 async function caption(text,seconds=5){await page.locator('#demo-caption').evaluate((el,t)=>{el.textContent=t},text);await page.waitForTimeout(seconds*1000);}
 await caption('按三个步骤看完整流程：配置评测、管理任务、对比结果。',5);
 await page.locator('nav a[href="#create"]').click();
 await page.locator('#models input[value="openvla"]').uncheck();await page.locator('#models input[value="fastwam"]').uncheck();
 await caption('第一步：以 VLA-Adapter 为例，同时选择原始精度和 RTN 四位量化。',6);
 await page.waitForFunction(()=>document.getElementById('estimate').textContent.includes('4,000'));
 await page.locator('#estimate').scrollIntoViewIfNeeded();
 await caption('选择四类 LIBERO 任务。本配置共 8 个组合、4,000 回合，页面自动计算规模。',6);
 await page.getByRole('button',{name:'查看本配置示例',exact:true}).click();
 await caption('第二步：查看任务。演示按刚才的配置筛选已完成实验，不会启动模型。',6);
 await page.locator('#demo-coverage').scrollIntoViewIfNeeded();await page.evaluate(()=>scrollBy(0,180));
 await caption('核对任务评测、资源测量和报告。真实运行时，也可查看进度、停止或续跑。',6);
 await page.getByRole('link',{name:'下一步：对比结果 →'}).click();await page.waitForSelector('.chart-grid');
 await page.locator('.chart-grid').scrollIntoViewIfNeeded();
 await caption('第三步：比较同一模型量化前后的成功率、查询耗时和显存占用。',7);
 await page.getByRole('button',{name:'空间关系',exact:true}).click();
 await caption('切换任务集合，查看量化对某一类操作任务的影响。',5);
 await page.locator('.downloads').scrollIntoViewIfNeeded();
 const download=page.waitForEvent('download');await page.getByText('下载完整报告',{exact:true}).click();await download;
 await caption('下载完整报告或数据表，保留本次选择对应的评测结果。',5);
 await page.locator('nav a[href="#create"]').click();
 await page.locator('#models input[value="openvla"]').check();await page.locator('#models input[value="fastwam"]').check();
 await page.getByRole('button',{name:'查看本配置示例',exact:true}).click();
 await page.getByRole('link',{name:'下一步：对比结果 →'}).click();await page.waitForSelector('.chart-grid');
 await page.locator('.chart-grid').scrollIntoViewIfNeeded();
 await caption('也可以一次对比三个模型：两种方法、四个任务集合，共 12,000 回合。',6);
 await page.locator('#demo-caption').evaluate(el=>el.hidden=true);await page.screenshot({path:path.join(output,'results.png'),fullPage:true});
 await page.locator('nav a[href="#tasks"]').click();await page.locator('#view-tasks').waitFor({state:'visible'});await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));await page.screenshot({path:path.join(output,'tasks.png'),fullPage:true});
 await page.locator('nav a[href="#create"]').click();await page.locator('#view-create').waitFor({state:'visible'});await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));await page.screenshot({path:path.join(output,'configuration.png'),fullPage:true});
 await page.locator('#demo-caption').evaluate(el=>el.hidden=false);
 await caption('选择配置 → 查看任务 → 对比结果。每一步都对应同一组实验。',5);
 const video=page.video();await context.close();await video.saveAs(path.join(output,'embodiq-demo.webm'));await browser.close();
 fs.writeFileSync(path.join(output,'recording.json'),JSON.stringify({page_errors:errors,source:'demo/index.html',read_only:true,real_evaluation_submitted:false,format:'webm',viewport:[1440,1000],caption_font_px:30},null,2));
 if(errors.length)throw Error(errors.join('\n'));console.log('recording complete: '+output);
})().catch(e=>{console.error(e);process.exit(1)});
